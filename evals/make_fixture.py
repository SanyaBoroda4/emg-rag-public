"""Generate the CI fixture: a small synthetic corpus with the same shape as
production, plus a golden set whose answers are computed from the generated
data (never hand-typed).

Everything is FABRICATED — customers, jobs, notes. No production data leaves
the server; the public repo stays clean. Deterministic (fixed seed): re-runs
produce byte-identical output.

Outputs (committed):
  evals/fixtures/fixture.sql         — jobs / job_areas / activities /
                                       chunks (explicit chunk_ids via
                                       OVERRIDING SYSTEM VALUE)
  evals/fixtures/fixture_golden.csv  — ~16 questions in golden-set format

CI embeds the 200 chunk texts at runtime with one Voyage call
(evals/fixtures/load_fixture.py); vectors are not committed.
"""

import csv
import random
import sys
from pathlib import Path

OUT_DIR = Path(__file__).resolve().parent / "fixtures"

rng = random.Random(4242)

CITIES = ["Croft Harbor", "Pelican Point", "Marsh Landing",
          "Cedarfield", "Old Quay"]
SALES = ["Rae Winslow", "Tomas Beck", "Ida Marsh"]
MATERIALS = ["Nebula Quartz", "Ashgrove Granite", "Tidewater Marble",
             "Iron Dune Quartzite", "Saltcreek Soapstone"]
FIRST = ["Avery", "Jordan", "Marlowe", "Quinn", "Sasha", "Rowan", "Ellis",
         "Devon", "Harper", "Blake", "Emerson", "Sage", "Reese"]
LAST = ["Toledano", "Vasquez", "Okafor", "Lindqvist", "Bram", "Castellano",
        "Whitfield", "Duarte", "Kowalski", "Mercer", "Ashby", "Fontaine"]
STATUSES = ["Complete", "Cancelled", "In Progress"]
ACT_TYPES = ["Template", "Install", "Measure", "Quote", "Follow Up",
             "Repair", "Invoice"]

NOTE_TEMPLATES = [
    "Customer asked to move the seam away from the {mat} island; confirmed new layout on site.",
    "Quote sent for {mat} countertops; customer comparing with another shop.",
    "No movement since the quote went out; follow up with {name} about next steps.",
    "Sink arrived cracked, replacement ordered; install pushed one week.",
    "{name} wants a different edge profile after seeing the sample, switching to eased edge.",
    "Field measure done; watch the out-of-level wall on the north run.",
    "Deposit received from {name}; slabs reserved at the yard.",
    "Repair visit: chip at the cooktop cutout filled and polished.",
    "Customer changed their mind about the sink, now wants an undermount double bowl.",
    "Template rescheduled twice; cabinets were not set on the first visit.",
    "Final walkthrough complete, {name} signed off; balance due on invoice.",
    "Backsplash added to scope after demo revealed damaged drywall.",
]


def esc(s):
    return s.replace("'", "''")


def main() -> int:
    OUT_DIR.mkdir(exist_ok=True)
    jobs = []
    for jid in range(1, 26):
        name = f"{rng.choice(FIRST)} {rng.choice(LAST)}"
        jobs.append({
            "job_id": jid, "job_name": name,
            "city": rng.choice(CITIES),
            "salesperson": rng.choice(SALES),
            "status": rng.choice(STATUSES),
            "creation_date": f"202{rng.randint(3, 5)}-"
                             f"{rng.randint(1, 12):02d}-"
                             f"{rng.randint(1, 28):02d}",
        })

    areas = []
    area_id_seq = 0
    for j in jobs:
        for _ in range(rng.randint(1, 2)):
            area_id_seq += 1
            areas.append({
                "form_id": 1000 + area_id_seq, "job_id": j["job_id"],
                "area_name": rng.choice(["Kitchen", "Vanity", "Island",
                                         "Laundry"]),
                "sq_ft": round(rng.uniform(15, 90), 1),
                "material": rng.choice(MATERIALS),
            })

    acts, chunks = [], []
    act_id = 0
    chunk_id = 0
    for j in jobs:
        n_acts = rng.randint(4, 7)
        for _ in range(n_acts):
            act_id += 1
            tmpl = rng.choice(NOTE_TEMPLATES)
            note = tmpl.format(mat=rng.choice(MATERIALS), name=j["job_name"])
            acts.append({"activity_id": act_id, "job_id": j["job_id"],
                         "type_name": rng.choice(ACT_TYPES),
                         "note": note})
            if chunk_id < 200:
                chunk_id += 1
                ctx = (f"{rng.choice(ACT_TYPES)} activity note on the "
                       f"{j['job_name']} job in {j['city']}, salesperson "
                       f"{j['salesperson']}, status {j['status']}.")
                chunks.append({"chunk_id": chunk_id, "job_id": j["job_id"],
                               "source_id": act_id, "raw": note,
                               "ctx": ctx})

    # ---- fixture.sql -------------------------------------------------
    lines = ["-- GENERATED by evals/make_fixture.py — do not hand-edit.",
             "-- Entirely synthetic data; safe for the public repo.", ""]
    for j in jobs:
        lines.append(
            "INSERT INTO jobs (job_id, job_name, account_name, salesperson, "
            "city, city_normalized, city_norm_source, job_status_name, "
            "process_name, creation_date) VALUES "
            f"({j['job_id']}, '{esc(j['job_name'])}', "
            f"'{esc(j['job_name'])}', '{j['salesperson']}', "
            f"'{j['city']}', '{j['city']}', 'name_map', "
            f"'{j['status']}', '{j['status']}', '{j['creation_date']}');")
    for j in jobs:  # job_forms parent rows for area FKs
        pass
    for a in areas:
        lines.append(
            "INSERT INTO job_forms (form_id, job_id, form_name, "
            "form_template_name, field_count) VALUES "
            f"({a['form_id']}, {a['job_id']}, '{a['area_name']}', "
            f"'Details', 15);")
        lines.append(
            "INSERT INTO job_areas (job_id, form_id, area_name, sq_ft, "
            "sq_ft_raw, material_name) VALUES "
            f"({a['job_id']}, {a['form_id']}, '{a['area_name']}', "
            f"{a['sq_ft']}, '{a['sq_ft']}', '{a['material']}');")
    for a in acts:
        lines.append(
            "INSERT INTO activities (activity_id, job_id, type_name, "
            "status_name, notes) VALUES "
            f"({a['activity_id']}, {a['job_id']}, '{a['type_name']}', "
            f"'Complete', '{esc(a['note'])}');")
    for c in chunks:
        lines.append(
            "INSERT INTO chunks (chunk_id, source_type, source_id, job_id, "
            "raw_text, context_text, text_hash, token_count) OVERRIDING "
            "SYSTEM VALUE VALUES "
            f"({c['chunk_id']}, 'activity_note', {c['source_id']}, "
            f"{c['job_id']}, '{esc(c['raw'])}', '{esc(c['ctx'])}', "
            f"'fixture-{c['chunk_id']}', {len(c['raw']) // 4});")
    (OUT_DIR / "fixture.sql").write_text("\n".join(lines) + "\n",
                                         encoding="utf-8")

    # ---- fixture_golden.csv (answers COMPUTED from the data) ---------
    golden = []

    def add(q, route, expected, rel_ids="", diff="easy"):
        golden.append({"id": str(len(golden) + 1), "question": q,
                       "route": route, "expected_answer": str(expected),
                       "relevant_ids": rel_ids, "source_of_truth":
                       "computed by make_fixture.py", "difficulty": diff,
                       "status": "verified", "notes": "synthetic fixture"})

    for city in CITIES[:3]:
        add(f"How many jobs are in {city}?", "structured",
            sum(1 for j in jobs if j["city"] == city))
    for mat in MATERIALS[:2]:
        n = len({a["job_id"] for a in areas if a["material"] == mat})
        add(f"How many jobs used {mat}?", "structured", n)
    add("How many jobs did Rae Winslow sell?", "structured",
        sum(1 for j in jobs if j["salesperson"] == "Rae Winslow"))
    biggest = max(areas, key=lambda a: a["sq_ft"])
    add("What is the largest area in square feet?", "structured",
        biggest["sq_ft"], diff="medium")

    def chunks_matching(substr):
        return sorted(c["chunk_id"] for c in chunks if substr in c["raw"])

    for phrase, question in [
        ("cracked", "Which jobs had a cracked sink delivered?"),
        ("changed their mind about the sink",
         "Where did the customer change their mind about the sink?"),
        ("No movement since the quote",
         "Which jobs went quiet after the quote was sent?"),
        ("out-of-level", "Any notes about out-of-level walls?"),
        ("edge profile", "Who switched edge profiles after seeing a sample?"),
    ]:
        ids = chunks_matching(phrase)
        if ids:
            add(question, "semantic", f"jobs with notes: chunks "
                f"{','.join(map(str, ids[:5]))}",
                ",".join(map(str, ids)), "medium")
    add("What is the tallest mountain in Europe?", "refuse",
        "decline — outside the data")

    with open(OUT_DIR / "fixture_golden.csv", "w", encoding="utf-8",
              newline="") as f:
        w = csv.DictWriter(f, fieldnames=["id", "question", "route",
                                          "expected_answer", "relevant_ids",
                                          "source_of_truth", "difficulty",
                                          "status", "notes"])
        w.writeheader()
        w.writerows(golden)

    print(f"fixture: {len(jobs)} jobs, {len(areas)} areas, {len(acts)} "
          f"activities, {len(chunks)} chunks, {len(golden)} golden questions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
